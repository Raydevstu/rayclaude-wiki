"""PostgreSQL compatibility store for durable production deployments."""

from __future__ import annotations

import json
import re
import threading
import time
from contextlib import contextmanager

try:
    import psycopg
except ImportError as exc:  # pragma: no cover - exercised in deployment environments
    raise RuntimeError("PostgreSQL persistence requires the psycopg package") from exc

from .store import GENESIS, SCHEMA, Store, _today
from .util import sha


_UPSERT_KEYS = {
    "runs": "id", "capsules": "run_id", "cache": "key", "approval_records": "id",
    "guard_write_audits": "id", "sandbox_jobs": "id", "tasks": "id", "jobs": "name",
}


class PostgresStore(Store):
    """Same store contract as SQLite, backed by a Render-managed PostgreSQL database."""

    backend = "postgres"

    def __init__(self, database_url: str):
        if not database_url.startswith(("postgres://", "postgresql://")):
            raise ValueError("TIER1_DATABASE_URL must be a PostgreSQL connection URL")
        self.db = psycopg.connect(database_url, autocommit=True)
        self.lock = threading.RLock()
        self._init_schema()

    def _init_schema(self):
        schema = SCHEMA.replace("INTEGER PRIMARY KEY", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        schema = schema.replace("CREATE TABLE IF NOT EXISTS", "CREATE TABLE IF NOT EXISTS")
        with self.lock:
            with self.db.cursor() as cur:
                for statement in schema.split(";"):
                    statement = statement.strip()
                    if statement:
                        cur.execute(statement)

    @staticmethod
    def _sql(sql: str) -> str:
        sql = sql.replace("INSERT OR REPLACE INTO", "INSERT INTO")
        sql = sql.replace("substr(", "substring(")
        return sql.replace("?", "%s")

    def _upsert(self, sql: str) -> str:
        match = re.search(r"INSERT INTO (\w+)\(([^)]*)\) VALUES", sql)
        if not match or match.group(1) not in _UPSERT_KEYS:
            return sql
        table, columns = match.group(1), [x.strip() for x in match.group(2).split(",")]
        key = _UPSERT_KEYS[table]
        updates = ", ".join(f"{col}=EXCLUDED.{col}" for col in columns if col != key)
        return f"{sql} ON CONFLICT ({key}) DO UPDATE SET {updates}"

    def x(self, sql: str, args=()):
        is_upsert = "INSERT OR REPLACE" in sql
        sql = self._sql(sql)
        if is_upsert:
            sql = self._upsert(sql)
        with self.lock:
            with self.db.cursor() as cur:
                cur.execute(sql, args)
                return cur

    def q(self, sql: str, args=()) -> list[dict]:
        with self.lock:
            with self.db.cursor() as cur:
                cur.execute(self._sql(sql), args)
                names = [d.name for d in cur.description]
                return [dict(zip(names, row)) for row in cur.fetchall()]

    @contextmanager
    def transaction(self):
        """Run a related set of store calls atomically on PostgreSQL."""
        with self.lock:
            with self.db.transaction():
                yield

    def ledger_append(self, run_id: str, kind: str, payload: dict) -> str:
        body = json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str)
        with self.lock:
            with self.db.transaction():
                with self.db.cursor() as cur:
                    cur.execute("SELECT seq, hash FROM ledger ORDER BY seq DESC LIMIT 1")
                    row = cur.fetchone()
                    prev = row[1] if row else GENESIS
                    seq = (row[0] + 1) if row else 1
                    ts = f"{time.time():.6f}"
                    h = sha(f"{seq}|{ts}|{run_id}|{kind}|{body}|{prev}")
                    cur.execute("INSERT INTO ledger(seq,ts,run_id,kind,payload,prev,hash) VALUES(%s,%s,%s,%s,%s,%s,%s)",
                                (seq, ts, run_id, kind, body, prev, h))
                    return h
